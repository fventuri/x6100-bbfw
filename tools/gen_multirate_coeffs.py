#!/usr/bin/env python3
"""Design the phase3-rx multirate decimation/interpolation FIRs (Georgy's plan)
and emit rx_multirate_coeffs.h. Equiripple (remez) anti-alias decimators + a
windowed interpolation prototype. All even-symmetric linear-phase, so the
CMSIS-DSP time-reversed coefficient convention is a no-op for them.

Chain (complex I/Q unless noted):
  decA  100 ->  50 kHz  /2   pass[0,8k]  stop[42k,50k]
  decB   50 ->  25 kHz  /2   pass[0,8k]  stop[17k,25k]
  dec25  25 -> 12.5 kHz /2   pass[0,5k]  stop[7.5k,12.5k]  (AM env real + SSB cplx)
  int8  12.5 -> 100 kHz /8   lowpass fc~6.0k @100k, DC gain 1 (matches old 1/L op pt)
"""
import os
import numpy as np
from scipy.signal import remez, firwin, freqz

# Write the header next to the firmware, regardless of CWD.
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                   "..", "firmwares", "phase3-rx", "rx_multirate_coeffs.h")

def atten_db(h, fs, stop_lo, stop_hi):
    w, H = freqz(h, worN=8192, fs=fs)
    m = (w >= stop_lo) & (w <= stop_hi)
    return -20*np.log10(np.max(np.abs(H[m])) + 1e-30)

def design_remez(name, fs, fpass, fstop, ntaps, target_db=58.0):
    """Grow ntaps (odd) until stopband >= target_db; return coeffs."""
    n = ntaps | 1
    while n < 201:
        h = remez(n, [0, fpass, fstop, fs/2], [1, 0], fs=fs)
        a = atten_db(h, fs, fstop, fs/2)
        if a >= target_db:
            break
        n += 2
    return h, a, n

def report(name, h, fs, fpass, fstop):
    w, H = freqz(h, worN=8192, fs=fs)
    pb = np.abs(H[w <= fpass])
    ripple = 20*np.log10(pb.max()/pb.min())
    att = atten_db(h, fs, fstop, fs/2)
    print(f"  {name:6s} ntaps={len(h):3d} sum={h.sum():.6f} "
          f"pb_ripple={ripple:.2f}dB stop_atten={att:.1f}dB")

filters = {}

print("Designing (equiripple decimators):")
hA, aA, nA = design_remez("decA", 100000, 8000, 42000, 13)
filters["RX_DECA"] = hA;  report("decA", hA, 100000, 8000, 42000)
hB, aB, nB = design_remez("decB", 50000, 8000, 17000, 23)
filters["RX_DECB"] = hB;  report("decB", hB, 50000, 8000, 17000)
h25, a25, n25 = design_remez("dec25", 25000, 5000, 7500, 31)
filters["RX_DEC25"] = h25; report("dec25", h25, 25000, 5000, 7500)

# Interpolator prototype: equiripple lowpass at the 100 kHz output rate,
# pass[0,5k] stop[7.5k,50k] (image region of the 12.5 kHz audio). numTaps must
# be a multiple of L=8 (arm_fir_interpolate_f32 requirement); grow until image
# rejection >= 35 dB (old OEM fir_int8_64 managed only ~18 dB). Normalize DC gain
# to 1 so the polyphase output keeps the OLD ~1/L passband level => the HW-tuned
# rx_audio_gain / HP-gain / AGC operating point transfers unchanged.
L = 8
def img_rej(h, fs=100000, pb=5000, img_lo=7500):
    w, H = freqz(h, worN=16384, fs=fs); A = np.abs(H)
    return 20*np.log10(A[w <= pb].max() / (A[w >= img_lo].max() + 1e-30))
nI = 64
while nI <= 160:
    hI = remez(nI, [0, 5000, 7500, 50000], [1, 0], fs=100000)
    if img_rej(hI) >= 35.0:
        break
    nI += 8
hI = hI / hI.sum()            # DC gain = 1 (old fir_int8_64 sum was 1.057 ~ 1)
filters["RX_INT8"] = hI
print(f"  int8   ntaps={len(hI):3d} sum={hI.sum():.6f} image_rej={img_rej(hI):.1f}dB "
      f"phaseLength={len(hI)//L}")

def emit_array(f, cname, macro_taps, h):
    f.write(f"#define {macro_taps} {len(h)}u\n")
    f.write(f"static const float {cname}[{len(h)}] = {{\n")
    for i in range(0, len(h), 4):
        row = h[i:i+4]
        f.write("    " + " ".join(f"{v:+.9e}f," for v in row) + "\n")
    f.write("};\n\n")

with open(OUT, "w") as f:
    f.write("""/*
 * x6100-bbfw -- Phase 3 RX multirate FIR coefficients.
 * GENERATED by tools/gen_multirate_coeffs.py (scipy remez/firwin). Do NOT hand-edit.
 *
 * Replaces the single-rate recovered-OEM chain (rx_fir_coeffs.h) with Georgy's
 * polyphase multirate chain, run through CMSIS-DSP arm_fir_decimate_f32 /
 * arm_fir_interpolate_f32 (MACs at the output/input rate only -- no per-sample
 * history shift). All decimators are even-symmetric linear-phase, so CMSIS's
 * time-reversed coefficient order is a no-op for them.
 *
 *   RX_DECA  : 100 ->  50 kHz  /2  complex  pass[0,8k]  stop[42k,50k]
 *   RX_DECB  :  50 ->  25 kHz  /2  complex  pass[0,8k]  stop[17k,25k]
 *   RX_DEC25 :  25 -> 12.5 kHz /2  AM-env (real) + SSB (complex)  pass[0,5k] stop[7.5k,12.5k]
 *   RX_INT8  : 12.5 -> 100 kHz /8  interpolation prototype, DC gain 1
 */
#ifndef X6100_RX_MULTIRATE_COEFFS_H
#define X6100_RX_MULTIRATE_COEFFS_H

""")
    emit_array(f, "rx_decA", "RX_DECA_TAPS", hA)
    emit_array(f, "rx_decB", "RX_DECB_TAPS", hB)
    emit_array(f, "rx_dec25", "RX_DEC25_TAPS", h25)
    emit_array(f, "rx_int8", "RX_INT8_TAPS", hI)
    f.write("#endif /* X6100_RX_MULTIRATE_COEFFS_H */\n")

print("\nwrote", os.path.normpath(OUT))
